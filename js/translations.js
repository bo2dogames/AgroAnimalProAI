/* Получаем сохранённый язык */
function getAgroLanguage() {
  try {
    const savedLanguage = localStorage.getItem(AGRO_LANGUAGE_KEY);

    if (['ru', 'kk', 'en', 'fr', 'zh'].includes(savedLanguage)) {
      return savedLanguage;
    }
  } catch (error) {
    console.warn('Не удалось прочитать язык:', error);
  }

  return 'ru';
}

/* Применяем переводы */
function applyAgroTranslations() {
  const language = getAgroLanguage();
  const translations = agroTranslations[language];

  document.documentElement.lang =
    language === 'kk' ? 'kk' : language;

  document.querySelectorAll('[data-i18n]').forEach(element => {
  const key = element.dataset.i18n;

  // Название фермы формируется отдельно из профиля пользователя
  if (key === 'welcomeFarmTitle') {
    return;
  }

  if (translations[key] !== undefined) {
    element.textContent = translations[key];
  }
});

  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const key = element.dataset.i18nPlaceholder;

    if (translations[key] !== undefined) {
      element.placeholder = translations[key];
    }
  });

  document.querySelectorAll('.language-btn').forEach(button => {
    button.classList.toggle(
      'active',
      button.dataset.lang === language
    );
  });
}

/* Переключаем язык */
function setAgroLanguage(language) {

  if (!['ru', 'kk', 'en', 'fr', 'zh'].includes(language)) {
    return;
  }

  try {
    localStorage.setItem(AGRO_LANGUAGE_KEY, language);
  } catch (error) {
    console.warn('Не удалось сохранить язык:', error);
  }

  applyAgroTranslations();
  // Обновляем приветствие с названием фермы
if (typeof renderOwnerProfile === 'function') {
  renderOwnerProfile();
}
  // Обновляем список участков при смене языка
if (typeof renderSavedFarmPlots === 'function') {
  renderSavedFarmPlots();
}
// Обновляем GPS и список животных при смене языка
if (typeof renderGpsAnimals === 'function') {
  renderGpsAnimals();
}
// Обновляем список участков
if (typeof renderSavedFarmPlots === 'function') {
  renderSavedFarmPlots();
}

// Обновляем GPS и список животных
if (typeof renderGpsAnimals === 'function') {
  renderGpsAnimals();
}
// Обновляем панель здоровья животных
if (typeof renderHealthDashboard === 'function') {
  renderHealthDashboard();
}
// Обновляем списки пород и окрасов
if (typeof updateAnimalOptions === 'function') {
  const speciesSelect = document.getElementById('animalSpecies');

  if (
    speciesSelect &&
    document.getElementById('animalBreed') &&
    document.getElementById('animalColor') &&
    animalOptions[speciesSelect.value]
  ) {
    updateAnimalOptions();
  }
}
}

/* Подключаем кнопки переключения */
document.querySelectorAll('.language-btn').forEach(button => {
  button.addEventListener('click', () => {
    setAgroLanguage(button.dataset.lang);
  });
});

